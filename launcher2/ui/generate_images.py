#!/usr/bin/env python3
"""Generate an embedded-images header: generate_images.py ASSET_DIR OUTPUT_HEADER"""
import pathlib
import sys

def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_images.py ASSET_DIR OUTPUT_HEADER")
    assets = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    chunks = ["// Generated by ui/generate_images.py; do not edit.\n#pragma once\n"]
    for filename, symbol in (("bg.png", "kBgPng"), ("logo.png", "kLogoPng"), ("controls_atlas.png", "kControlsAtlasPng"), ("avatar.png", "kAvatarPng")):
        data = (assets / filename).read_bytes()
        body = ",".join(str(b) for b in data)
        chunks.append("static const unsigned char %s[] = {%s};\n" % (symbol, body))
        chunks.append("static const unsigned long %sSize = %d;\n" % (symbol, len(data)))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(chunks), encoding="utf-8")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
